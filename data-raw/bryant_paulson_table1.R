## ---- Assemble the tidy long data set ----------------------------------
blocks <- list(
  list(p = 1, alpha = 0.05, m = p1_a05),
  list(p = 1, alpha = 0.01, m = p1_a01),
  list(p = 2, alpha = 0.05, m = p2_a05),
  list(p = 2, alpha = 0.01, m = p2_a01),
  list(p = 3, alpha = 0.05, m = p3_a05),
  list(p = 3, alpha = 0.01, m = p3_a01)
)
rows <- lapply(blocks, function(b) data.frame(
  p = b$p, alpha = b$alpha,
  nu = rep(nu_values, times = length(k_values)),
  k  = rep(k_values, each = length(nu_values)),
  critical_value = as.vector(b$m)))
bryant_paulson_table1 <- do.call(rbind, rows)
bryant_paulson_table1 <- bryant_paulson_table1[order(
  bryant_paulson_table1$p, bryant_paulson_table1$alpha,
  bryant_paulson_table1$nu, bryant_paulson_table1$k), ]
rownames(bryant_paulson_table1) <- NULL

