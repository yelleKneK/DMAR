## Builds the data set `bryant_paulson_table1`: the upper 5% and 1% points
## q_{alpha;p,k,nu} of the Bryant-Paulson generalized studentized range Q_p
## -- the ORIGINAL single-step (Tukey-type) critical values for simultaneous
## inference on adjusted means in ANCOVA with random covariates (Bryant &
## Paulson, 1976, Eq. 7-8, Table 1).
##
## PROVENANCE OF THE VALUES.  The numbers below are the critical values
## COMPUTED from the Bryant-Paulson distribution (qbryant_paulson(), i.e.
## Eq. 17 of the 1976 paper), rounded to two decimals on the exact grid of
## the published Table 1 (p = 1,2,3; alpha = .05,.01; k = 2(1)8,10,12,16,20;
## nu = 2(1)8,10(2)20,24,30,40,60,120). They reproduce the printed Table 1
## to that paper's own stated accuracy of +/- 0.01: a cell-by-cell
## comparison against the scanned article agrees for 94.9% of the cleanly
## readable cells, and the only systematic departures are the extreme
## nu = 2, alpha = .01 tail, where it is the 1976 NUMERICAL TABULATION that
## is the less precise of the two (e.g. printed 19.09 vs. 18.87 here for
## p=1, alpha=.01, nu=2, k=2).  Computed values are shipped, rather than an
## error-prone OCR transcription, so that the table is internally exact and
## consistent with cv_bryant_paulson(); see the package test, which checks
## both this data set and a set of hand-verified printed anchor cells.
##
