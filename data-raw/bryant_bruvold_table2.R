  list(p = 1, alpha = 0.05, m = p1_a05),
  list(p = 1, alpha = 0.01, m = p1_a01),
  list(p = 2, alpha = 0.05, m = p2_a05),
  list(p = 2, alpha = 0.01, m = p2_a01),
  list(p = 3, alpha = 0.05, m = p3_a05),
  list(p = 3, alpha = 0.01, m = p3_a01)
