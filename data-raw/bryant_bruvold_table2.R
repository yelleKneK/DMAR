rows <- lapply(blocks, function(b) {
  idx <- which(!is.na(b$m), arr.ind = TRUE)
  data.frame(p = b$p, alpha = b$alpha,
             nu = nu_values[idx[, "nu"]], k = k_values[idx[, "k"]],
             critical_value = b$m[idx])
})
bryant_bruvold_table2 <- do.call(rbind, rows)
bryant_bruvold_table2 <- bryant_bruvold_table2[order(
  bryant_bruvold_table2$p, bryant_bruvold_table2$alpha,
  bryant_bruvold_table2$nu, bryant_bruvold_table2$k), ]
rownames(bryant_bruvold_table2) <- NULL

